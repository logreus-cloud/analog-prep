// Обезличенная статистика спроса.
//
// ВАЖНО, что здесь НЕ хранится: текст запроса, IP, идентификатор сессии, время
// обращения. Только счётчик по действующему веществу.
//
// Причина в том, что название препарата — это диагноз. «Левотироксин» означает
// заболевание щитовидной железы, «метформин» — диабет. Строка запроса вместе с
// адресом или временем перестаёт быть обезличенной ровно в тот момент, когда
// пользователь на сайте один. Поэтому сохраняется агрегат, из которого нельзя
// восстановить ни человека, ни отдельное обращение.
//
// Хранилище в памяти процесса и обнуляется при перезапуске. Для MVP это честнее
// файла: ничего не переживает деплой, и утекать нечему.
const counts = new Map();

export function record(substanceId) {
  if (!substanceId) return;
  counts.set(substanceId, (counts.get(substanceId) ?? 0) + 1);
}

export function top(limit = 3) {
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([substanceId, count]) => ({ substanceId, count }));
}

export const total = () => [...counts.values()].reduce((sum, n) => sum + n, 0);
